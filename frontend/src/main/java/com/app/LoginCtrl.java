package com.app;

import javafx.event.ActionEvent;
import javafx.fxml.FXML;
import javafx.fxml.FXMLLoader;
import javafx.scene.Node;
import javafx.scene.Parent;
import javafx.scene.Scene;
import javafx.scene.control.Label;
import javafx.scene.control.TextField;
import javafx.stage.Stage;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;

/**
 * Controller class for managing user login functionality in the JavaFX application.
 * Validates employee credentials against the database, sets up the active session, 
 * and switches the application view to the main cashier interface based on user roles.
 * 
 * @author Christopher Jermia
 * @author Kenny Le
 * @author Jeffrey Yu
 * @author Ethan Faulkner
 * @author Andrew Schrick
 * @version 1.0
 */
public class LoginCtrl {
    
    /** Text field for entering the employee ID. */
    @FXML 
    private TextField employeeIdField;
    
    /** Label used to display login error messages to the user. */
    @FXML 
    private Label errorLabel;

    /**
     * Handles the login action triggered by the user clicking the login button.
     * Validates input, queries the database for employee details, updates the session,
     * and loads the cashier dashboard with appropriate access privileges.
     * 
     * @param event The ActionEvent generated by the login button click.
     */
    @FXML
    private void handleLogin(ActionEvent event) {
        String idText = employeeIdField.getText().trim();
        
        if (idText.isEmpty()) {
            errorLabel.setText("Please enter your Employee ID.");
            return;
        }

        String sql = "SELECT name, role FROM employees WHERE id = ?";

        // Establish database connection and prepare the query to prevent SQL injection
        try (Connection conn = Database.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {
            
            stmt.setInt(1, Integer.parseInt(idText));
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                String role = rs.getString("role");
                boolean isManager = "manager".equalsIgnoreCase(role);
                int employeeId = Integer.parseInt(idText);
                
                
                Session.employeeId = employeeId; // Store the authenticated employee ID in the global session

                FXMLLoader loader = new FXMLLoader(getClass().getResource("/cashier.fxml"));
                Parent root = loader.load();
                
                CashierCtrl cashierCtrl = loader.getController();
                cashierCtrl.setManagerAccess(isManager);
                
                Stage stage = (Stage) ((Node) event.getSource()).getScene().getWindow();
                stage.setScene(new Scene(root, 1280, 720));
                stage.show();
                
            } else {
                // Display error if no employee exists with the provided ID
                errorLabel.setText("Invalid Employee ID");
            }
            
        } catch (NumberFormatException e) {
            // Handle cases where the input is not a valid integer
            errorLabel.setText("ID must be a number");
        } catch (Exception e) {
            e.printStackTrace();
            errorLabel.setText("Database error occurred");
        }
    }
}